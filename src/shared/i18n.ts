export function normalizeLang(lang?: string): string {
  if (!lang) return 'en';
  const clean = lang.trim().toLowerCase();
  if (clean.startsWith('zh-cn') || clean === 'cn' || clean === 'zh-hans') return 'cn';
  if (clean.startsWith('zh') || clean === 'zh-tw' || clean === 'zh-hk' || clean === 'zh-hant') return 'zh';
  if (clean.startsWith('pt')) return 'pt';
  if (clean.startsWith('ko')) return 'ko';
  if (clean.startsWith('ar')) return 'ar';
  if (clean.startsWith('es')) return 'es';
  if (clean.startsWith('uk')) return 'uk';
  if (clean.startsWith('ja')) return 'ja';
  if (clean.startsWith('th')) return 'th';
  if (clean.startsWith('he')) return 'he';
  if (clean.startsWith('pl')) return 'pl';
  if (clean.startsWith('el')) return 'el';
  return 'en';
}

